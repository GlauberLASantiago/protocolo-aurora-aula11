 const gsap={registerPlugin:p=>calls.push(['plugin',p]),context:fn=>{const ctx={reverted:false,add:fn=>fn(),revert(){this.reverted=true;}};contexts.push(ctx);fn();return ctx;},from:(target,vars)=>{calls.push(['from',target,vars]);return {};},fromTo:(target,from,to)=>calls.push(['fromTo',target,from,to])};
 const Flip={getState:targets=>{calls.push(['capture',targets]);return {targets};},from:(state,vars)=>{calls.push(['flip',state,vars]);return {};}};
